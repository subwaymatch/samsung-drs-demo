// Builds lib/region-map.ts, the dot map behind the Sales region field.
//
//   node scripts/region-map.mjs [step-in-degrees]
//
// Downloads Natural Earth's 1:110m countries (public domain), samples them on a
// grid of dots and tags each land dot with the sales region it belongs to. The
// output is plain data, so the app needs no map library at runtime.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson';
const STEP = Number(process.argv[2]) || 4;
// Northern tip of Greenland to Cape Horn; Antarctica is left out.
const TOP = 82;
const BOTTOM = -56;

const CIS = new Set(['RUS', 'BLR', 'UKR', 'MDA', 'ARM', 'AZE', 'GEO', 'KAZ', 'KGZ', 'TJK', 'TKM', 'UZB']);

/** One letter per sales region; "o" is land outside every named region. */
function regionOf(p) {
  const a3 = p.ADM0_A3;
  if (a3 === 'KOR') return 'k';
  if (a3 === 'JPN') return 'j';
  if (a3 === 'CHN') return 'c';
  if (CIS.has(a3)) return 'i';
  if (p.SUBREGION === 'South-Eastern Asia') return 's';
  if (p.CONTINENT === 'Europe') return 'e';
  if ((p.CONTINENT === 'North America' || p.CONTINENT === 'South America') && a3 !== 'GRL') return 'a';
  if (p.CONTINENT === 'Africa' || p.SUBREGION === 'Western Asia' || a3 === 'IRN') return 'm';
  if (p.CONTINENT === 'Antarctica') return null;
  return 'o';
}

const inRing = (x, y, ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const inPolygon = (x, y, rings) => inRing(x, y, rings[0]) && !rings.slice(1).some(h => inRing(x, y, h));

const geo = await (await fetch(SOURCE)).json();
// One shape per polygon, so overseas parts of a country can sit in the region
// they are actually in (French Guiana belongs to France but lies in South America).
const shapes = geo.features
  .flatMap(f => {
    const code = regionOf(f.properties);
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    return polys.map(rings => {
      const pts = rings[0];
      const box = [Math.min(...pts.map(p => p[0])), Math.min(...pts.map(p => p[1])), Math.max(...pts.map(p => p[0])), Math.max(...pts.map(p => p[1]))];
      const overseas = code === 'e' && box[2] < -25;
      return { code: overseas ? 'a' : code, rings, box };
    });
  })
  .filter(s => s.code);

const regionAt = (x, y) => {
  for (const s of shapes) {
    if (x < s.box[0] || x > s.box[2] || y < s.box[1] || y > s.box[3]) continue;
    if (inPolygon(x, y, s.rings)) return s.code;
  }
  return null;
};

// Each dot looks at a 3x3 patch of its cell and takes the most common region, so
// coastlines and small countries still show up.
const cols = Math.round(360 / STEP);
const rows = Math.round((TOP - BOTTOM) / STEP);
const grid = [];
for (let r = 0; r < rows; r++) {
  let line = '';
  for (let c = 0; c < cols; c++) {
    const counts = {};
    for (let i = 0; i < 3; i++)
      for (let j = 0; j < 3; j++) {
        const code = regionAt(-180 + (c + (i + 0.5) / 3) * STEP, TOP - (r + (j + 0.5) / 3) * STEP);
        if (code) counts[code] = (counts[code] || 0) + 1;
      }
    const land = Object.values(counts).reduce((a, b) => a + b, 0);
    line += land >= 3 ? Object.entries(counts).sort((a, b) => b[1] - a[1])[0][0] : '.';
  }
  grid.push(line);
}

// Korea and Japan are smaller than a dot or two; make sure each has at least one.
for (const [code, lon, lat] of [['k', 127.8, 36.5], ['j', 138.5, 36.5]]) {
  if (grid.some(l => l.includes(code))) continue;
  const c = Math.floor((lon + 180) / STEP), r = Math.floor((TOP - lat) / STEP);
  grid[r] = grid[r].slice(0, c) + code + grid[r].slice(c + 1);
}

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'region-map.ts');
writeFileSync(
  out,
  `// Generated by scripts/region-map.mjs from Natural Earth 1:110m countries (public
// domain). Do not edit by hand.
//
// A ${STEP}-degree dot grid from ${TOP}N to ${-BOTTOM}S, ${cols} columns by ${rows} rows, one character
// per dot: k Korea, j Japan, c China, s Southeast Asia, a Americas, e Europe,
// i CIS, m Middle East and Africa, o other land, . sea.

export const MAP_STEP = ${STEP};
export const MAP_ROWS = [
${grid.map(l => `  '${l}'`).join(',\n')}
];
`
);
console.log(`Wrote ${out}: ${cols}x${rows}, ${grid.join('').replace(/\./g, '').length} land dots`);
